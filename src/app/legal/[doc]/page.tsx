function isDoc(value: string): value is LegalDoc {
  return value in LEGAL_DOCS;
}

export function generateStaticParams() {
  return Object.keys(LEGAL_DOCS).map((doc) => ({ doc }));
}

export async function generateMetadata({ params }: PageProps<"/legal/[doc]">): Promise<Metadata> {
  const { doc } = await params;
  return isDoc(doc) ? { title: LEGAL_DOCS[doc].title } : {};
}

export default async function LegalPage({ params }: PageProps<"/legal/[doc]">) {
  const { doc } = await params;
  if (!isDoc(doc)) notFound();
  return (
    <article className="legal flex flex-col gap-4">
      <p className="rounded-[var(--radius-control)] border border-ink bg-surface p-3 text-[15px] font-semibold">
        Черновик — проверить у юриста.
      </p>
      <h1 className="font-display text-[28px] leading-tight font-semibold">{LEGAL_DOCS[doc].title}</h1>
      <p className="text-sm text-ink-soft">Версия {LEGAL_DOCS[doc].version}</p>
      {CONTENT[doc]}
    </article>
  );
}
